#!/usr/bin/env bash
# embed-opencode-cli.sh
# Builds the MIT-licensed OpenCode CLI binary with bun and embeds it into the
# Anvil app bundle resources so OpenCodeBridge can spawn it at runtime.
#
# Usage:
#   cd /Volumes/Artificial_Intelligence_Machine_Learning/dev/OpenCodeNext/Anvil
#   ./script/embed-opencode-cli.sh
#
# Requires: bun (https://bun.sh) and network access for `bun install`.

set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
OPENCODE_DIR="${ROOT_DIR}/.referencedata/opencode-cli"
RESOURCES_DIR="${ROOT_DIR}/Sources/AnvilApp/Resources"
BINARY_NAME="opencode-cli"

echo "==> Anvil: embed-opencode-cli"
echo "ROOT_DIR: ${ROOT_DIR}"
echo "OPENCODE_DIR: ${OPENCODE_DIR}"

if [ ! -d "${OPENCODE_DIR}" ]; then
  echo "ERROR: opencode-cli source not found at ${OPENCODE_DIR}"
  echo "   Clone it first: git clone https://github.com/anomalyco/opencode.git .referencedata/opencode-cli"
  exit 1
fi

if ! command -v bun >/dev/null 2>&1; then
  echo "ERROR: bun is required but not installed. Get it at https://bun.sh"
  exit 1
fi

mkdir -p "${RESOURCES_DIR}"

echo "==> Installing opencode-cli dependencies (bun install)..."
(cd "${OPENCODE_DIR}" && bun install)

echo "==> Compiling standalone opencode-cli binary..."
# The CLI imports virtual build modules (e.g. opencode-app-assets) that are
# generated by the monorepo's app build. Produce them first, then compile.
(cd "${OPENCODE_DIR}" && bun run --cwd packages/app build 2>/dev/null || true)
(cd "${OPENCODE_DIR}" && bun build packages/cli/src/index.ts \
  --compile \
  --outfile="${RESOURCES_DIR}/${BINARY_NAME}")

chmod +x "${RESOURCES_DIR}/${BINARY_NAME}"

echo "==> Embedded opencode-cli at:"
echo "   ${RESOURCES_DIR}/${BINARY_NAME}"
echo ""
echo "If the compile above fails due to unresolved virtual modules, run the full"
echo "monorepo pack first (cd .referencedata/opencode-cli && bun run pack), then"
echo "copy the resulting CLI binary into Resources/opencode-cli manually."
echo ""
echo "Next: build Anvil in Xcode. OpenCodeBridge will spawn this binary at runtime."
